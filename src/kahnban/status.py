"""Board projections: ``plans/STATUS.md``, ``plans/status.json``, and ``plans/board.json``.

All projection files are regenerated wholesale on every transition and are never
edited by hand — the column folders remain the sole ground truth (D8).  Titles come
from frontmatter, never from splitting filenames on ``-`` (a v3 defect that
broke on slugs containing digits).
"""

from __future__ import annotations

import json
import statistics
from collections.abc import Iterable, Mapping, Sequence
from datetime import datetime
from pathlib import Path
from typing import Any

from kahnban import __version__

FIELDS = ("id", "title", "status", "owner", "branch", "worktree", "updated", "column")

Record = Mapping[str, Any]


def _sort_key(record: Record) -> tuple[str, int, str]:
    """Deterministic order: prefix, then numeric id, then raw id."""
    ticket_id = record.get("id", "")
    prefix, _, number = ticket_id.rpartition("-")
    try:
        numeric = int(number)
    except ValueError:
        numeric = 0
    return (prefix, numeric, ticket_id)


def _grouped(
    records: Iterable[Record], columns: Sequence[str]
) -> dict[str, list[Record]]:
    grouped: dict[str, list[Record]] = {column: [] for column in columns}
    for record in records:
        grouped.setdefault(record.get("column", ""), []).append(record)
    for bucket in grouped.values():
        bucket.sort(key=_sort_key)
    return grouped


def _escape_cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ").strip()


def render_markdown(
    records: Iterable[Record],
    columns: Sequence[str],
    *,
    timestamp: datetime,
    project_name: str = "",
) -> str:
    grouped = _grouped(records, columns)
    heading = f"# Board Status{f' — {project_name}' if project_name else ''}"
    lines = [
        heading,
        "",
        "<!-- GENERATED BY kahnban. Do not edit; run `kahnban sync`. -->",
        "",
        f"Generated: {timestamp.strftime('%Y-%m-%d %H:%M')}",
        "",
        "## Column counts",
        "",
        "| Column | Tickets |",
        "| :--- | ---: |",
    ]
    for column in columns:
        lines.append(f"| {column} | {len(grouped.get(column, []))} |")
    lines.append("")

    for column in columns:
        bucket = grouped.get(column, [])
        lines.extend([f"## {column} ({len(bucket)})", ""])
        if not bucket:
            lines.extend(["_empty_", ""])
            continue
        lines.extend(
            [
                "| ID | Title | Owner | Branch | Updated |",
                "| :--- | :--- | :--- | :--- | :--- |",
            ]
        )
        for record in bucket:
            lines.append(
                "| {id} | {title} | {owner} | {branch} | {updated} |".format(
                    id=_escape_cell(record.get("id", "")),
                    title=_escape_cell(record.get("title", "")),
                    owner=_escape_cell(record.get("owner", "")) or "-",
                    branch=_escape_cell(record.get("branch", "")) or "-",
                    updated=_escape_cell(record.get("updated", "")) or "-",
                )
            )
        lines.append("")

    return "\n".join(lines).rstrip("\n") + "\n"


def render_json(
    records: Iterable[Record],
    columns: Sequence[str],
    *,
    timestamp: datetime,
) -> str:
    grouped = _grouped(records, columns)
    payload = {
        "generated": timestamp.strftime("%Y-%m-%dT%H:%M:%S"),
        "generator": "kahnban",
        "columns": [
            {
                "name": column,
                "count": len(grouped.get(column, [])),
                "tickets": [
                    {field: record.get(field, "") for field in FIELDS}
                    for record in grouped.get(column, [])
                ],
            }
            for column in columns
        ],
        "metrics": _metrics(records),
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def _metrics(records: Iterable[Record]) -> dict[str, Any]:
    """Per-ticket counts plus how often done work passed first time, and how fast."""
    per_ticket = {
        str(record["id"]): dict(record["metrics"])
        for record in sorted(records, key=_sort_key)
        if record.get("metrics")
    }
    done = [m for m in per_ticket.values() if m.get("cycle_hours") is not None]
    clean = [m for m in done if m["verify_attempts"] <= 1 and not m["rejections"]]
    return {
        "done": len(done),
        "first_pass_yield": round(len(clean) / len(done), 2) if done else None,
        "median_cycle_hours": statistics.median(m["cycle_hours"] for m in done) if done else None,
        "tickets": per_ticket,
    }


def render_board_json(
    records: Iterable[Record],
    columns: Sequence[str],
    *,
    timestamp: datetime,
    project_name: str = "",
    wip_limit: int = 3,
) -> str:
    grouped = _grouped(records, columns)
    tickets_by_id: dict[str, dict[str, Any]] = {}
    board_columns = []

    for column in columns:
        col_tickets: list[dict[str, Any]] = []
        for record in grouped.get(column, []):
            ticket_id = str(record.get("id", ""))
            depends_on = record.get("depends_on", [])
            if isinstance(depends_on, str):
                depends_on = [d.strip() for d in depends_on.split(",") if d.strip()]
            blast_radius = record.get("blast_radius", [])
            if isinstance(blast_radius, str):
                blast_radius = [b.strip() for b in blast_radius.split(",") if b.strip()]

            entry: dict[str, Any] = {
                "id": ticket_id,
                "title": str(record.get("title", "")),
                "status": str(record.get("status", "")),
                "column": str(record.get("column", column)),
                "owner": str(record.get("owner", "")),
                "branch": str(record.get("branch", "")),
                "worktree": str(record.get("worktree", "")),
                "description": str(record.get("description", "")),
                "depends_on": depends_on,
                "blocked_on": str(record.get("blocked_on", "")),
                "blast_radius": blast_radius,
                "updated": str(record.get("updated", "")),
            }
            col_tickets.append(entry)
            if ticket_id:
                tickets_by_id[ticket_id] = entry

        board_columns.append(
            {
                "name": column,
                "count": len(col_tickets),
                "tickets": col_tickets,
            }
        )

    payload = {
        "generated": timestamp.strftime("%Y-%m-%dT%H:%M:%S"),
        "generator": f"kahnban-v{__version__}",
        "project": project_name,
        "wip_limit": wip_limit,
        "columns": board_columns,
        "tickets_by_id": tickets_by_id,
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def write(
    plans_dir: Path,
    records: Iterable[Record],
    columns: Sequence[str],
    *,
    timestamp: datetime,
    project_name: str = "",
    wip_limit: int = 3,
) -> list[Path]:
    """Write projections (STATUS.md, status.json, board.json); returns written paths."""
    materialized = list(records)
    plans_dir.mkdir(parents=True, exist_ok=True)
    markdown_path = plans_dir / "STATUS.md"
    json_path = plans_dir / "status.json"
    board_json_path = plans_dir / "board.json"

    from kahnban.core import write_text_atomic

    write_text_atomic(
        markdown_path,
        render_markdown(
            materialized, columns, timestamp=timestamp, project_name=project_name
        ),
    )
    write_text_atomic(
        json_path,
        render_json(materialized, columns, timestamp=timestamp),
    )
    board_json_payload = render_board_json(
        materialized,
        columns,
        timestamp=timestamp,
        project_name=project_name,
        wip_limit=wip_limit,
    )
    write_text_atomic(
        board_json_path,
        board_json_payload,
    )

    written = [markdown_path, json_path, board_json_path]

    # Optional bridge for external/third-party viewers expecting a root .kanban/board.json layout
    alt_kanban_dir = plans_dir.parent / ".kanban"
    if alt_kanban_dir.is_dir():
        alt_board_json = alt_kanban_dir / "board.json"
        write_text_atomic(
            alt_board_json,
            board_json_payload,
        )
        written.append(alt_board_json)

    return written
